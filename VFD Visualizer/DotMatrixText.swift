import SwiftUI

// Draws short text as 5x7 dots, like the character cells on a VFD panel.
// Used for the status label, CPU readout, frequency labels, and Now Playing; longer text stays in the system font.
struct DotMatrixText: View {
    let text: String
    var color: Color
    // Distance between dot centers, in points
    var pitch: CGFloat = 1.75
    // Always leave room below the line for g, j, p, q, and y, so changing text never shifts up or down
    var reservesDescenders = false

    var body: some View {
        // Draw the simplified text, so accents and typographic marks still get dots
        let shown = DotMatrixText.normalized(text)
        let size = DotMatrixText.size(of: text, pitch: pitch, reservesDescenders: reservesDescenders)
        Canvas { context, _ in
            // Each dot fills most of its cell, leaving a small gap between dots
            let radius = pitch * 0.38
            for (index, character) in shown.enumerated() {
                for (row, bits) in DotMatrixText.glyph(for: character).enumerated() {
                    for (column, bit) in bits.enumerated() where bit == "1" {
                        // Each character is 5 dots wide, plus one dot of space before the next
                        let x = (CGFloat(index * 6 + column) + 0.5) * pitch
                        let y = (CGFloat(row) + 0.5) * pitch
                        let dot = CGRect(x: x - radius, y: y - radius, width: radius * 2, height: radius * 2)
                        context.fill(Path(ellipseIn: dot), with: .color(color))
                    }
                }
            }
        }
        .frame(width: size.width, height: size.height)
        // A soft glow around the dots, like phosphor
        .shadow(color: color.opacity(0.5), radius: pitch)
        // Drawn dots aren't text to VoiceOver, so give it the original words
        .accessibilityElement()
        .accessibilityLabel(text)
    }

    // Width and height of the dots for this text: 7 rows, or 9 when there are tails below the line
    static func size(of text: String, pitch: CGFloat, reservesDescenders: Bool = false) -> CGSize {
        let shown = normalized(text)
        let rows = reservesDescenders || hasDescenders(shown) ? 9 : 7
        return CGSize(width: CGFloat(max(0, shown.count * 6 - 1)) * pitch, height: CGFloat(rows) * pitch)
    }

    // Whether any character hangs below the line
    static func hasDescenders(_ text: String) -> Bool {
        text.contains { glyph(for: $0).count > 7 }
    }

    // The 5x7 pattern for a character, top row first. Characters without one are left blank.
    static func glyph(for character: Character) -> [String] {
        glyphs[character] ?? blank
    }

    static let blank = Array(repeating: "00000", count: 7)

    // Typographic marks that song titles often use, swapped for ones that have dot shapes
    static let substitutions: [Character: String] = [
        "\u{2013}": "-", "\u{2014}": "-",                    // En and em dashes
        "\u{2018}": "'", "\u{2019}": "'",                    // Curly single quotes
        "\u{201C}": "\"", "\u{201D}": "\"",                  // Curly double quotes
        "\u{2026}": "...",                                   // Ellipsis
        "\u{00A0}": " ",                                     // Non-breaking space
    ]

    // The text as it will be drawn: typographic marks simplified, and accents dropped
    // (João becomes Joao), as hardware dot-matrix displays do
    static func normalized(_ text: String) -> String {
        var shown = ""
        for character in text {
            if let swap = substitutions[character] {
                shown += swap
            } else if glyphs[character] != nil {
                // Keep letters with their own shape, such as Й, which is a separate letter from И
                shown.append(character)
            } else {
                // Otherwise drop the marks: é becomes e
                shown += String(character).folding(options: .diacriticInsensitive, locale: Locale(identifier: "en_US_POSIX"))
            }
        }
        return shown
    }

